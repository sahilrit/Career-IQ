"""Experiment: an A/B test across one kind of content the platform
already generates elsewhere — this package doesn't generate resumes,
emails, or proposals itself, it just tracks which variant of content
generated by earlier phases performs better in the real world.
"""

from __future__ import annotations

import uuid
from enum import StrEnum

from pydantic import BaseModel, Field

from careeros_common import DocumentStore

_ENTITY_TYPE = "experiment"


class ExperimentType(StrEnum):
    RESUME = "resume"
    EMAIL = "email"
    LINKEDIN = "linkedin"
    PORTFOLIO = "portfolio"
    PROPOSAL = "proposal"
    SUBJECT_LINE = "subject_line"


class ExperimentStatus(StrEnum):
    RUNNING = "running"
    COMPLETED = "completed"


class Experiment(BaseModel):
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    experiment_type: ExperimentType
    name: str
    status: ExperimentStatus = ExperimentStatus.RUNNING


class ExperimentRepository:
    def __init__(self, store: DocumentStore) -> None:
        self._store = store

    def save(self, experiment: Experiment) -> None:
        self._store.put(_ENTITY_TYPE, experiment.id, experiment.model_dump(mode="json"))

    def load(self, experiment_id: str) -> Experiment:
        return Experiment.model_validate(self._store.get(_ENTITY_TYPE, experiment_id))

    def list_all(self) -> list[Experiment]:
        return [Experiment.model_validate(data) for data in self._store.list(_ENTITY_TYPE)]
